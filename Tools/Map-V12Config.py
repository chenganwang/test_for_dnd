"""Map V12 design examples into this project's V12CombatConfig contract.

The design JSON is never overwritten or loaded as a Unity object. Re-run this
mapping after editing its explicit field map; compile after changing runtime data.
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / '补丁/Unity_ActionCRPG_V12_开发任务包/ActionCRPG_V12_Design/V12_设计参数示例.json'
target = ROOT / 'Assets/CombatV051/Resources/V12CombatConfig.json'
generated = ROOT / 'Assets/CombatV051/Domain/V12ConfigJson.Generated.cs'
mapping = {
    'markSeconds': ('evan_annotation','duration_sim_seconds'), 'markMultiplier': ('evan_annotation','incoming_damage_multiplier'),
    'markRange': ('evan_annotation','range_m'), 'markWindup': ('evan_annotation','windup_sim_seconds'), 'markCooldown': ('evan_annotation','cooldown_sim_seconds'),
    'echoCoefficient': ('evan_margin','echo_base_attack_coefficient'), 'echoInterval': ('evan_margin','internal_cooldown_sim_seconds'),
    'finalCoefficient': ('evan_final_note','damage_base_attack_coefficient'), 'finalRange': ('evan_final_note','range_m'), 'finalWindup': ('evan_final_note','windup_sim_seconds'),
    'chaseRange': ('mira_pursuit','maximum_travel_m'), 'chaseCooldown': ('mira_pursuit','cooldown_sim_seconds'), 'chaseCoefficient': ('mira_pursuit','damage_base_attack_coefficient'),
    'readinessSeconds': ('mira_momentum','ready_duration_sim_seconds'), 'readinessMultiplier': ('mira_momentum','next_basic_damage_multiplier'),
    'breakCoefficient': ('mira_breaker','damage_base_attack_coefficient'), 'breakRange': ('mira_breaker','range_m'), 'breakWindup': ('mira_breaker','windup_sim_seconds'), 'breakDamage': ('mira_breaker','break_damage_if_supported'),
    'seedRange': ('fien_seed','range_m'), 'seedWindup': ('fien_seed','windup_sim_seconds'), 'seedCooldown': ('fien_seed','cooldown_sim_seconds'),
    'parasiteSeconds': ('fien_seed','duration_sim_seconds'), 'parasiteInterval': ('fien_seed','tick_interval_sim_seconds'), 'parasiteCoefficient': ('fien_seed','tick_base_attack_coefficient'),
    'groveRange': ('fien_grove','cast_range_m'), 'groveWindup': ('fien_grove','windup_sim_seconds'), 'groveRadius': ('fien_grove','radius_m'),
    'groveSeconds': ('fien_grove','duration_sim_seconds'), 'groveHealFraction': ('fien_grove','ally_heal_max_hp_fraction_per_sim_second'),
    'entangleMultiplier': ('fien_grove','movement_multiplier'), 'groveMaximumEnemies': ('fien_grove','maximum_enemies_tagged_per_cast'),
}
local = {'chaseWindup': .25, 'chaseMinimumTravel': .35, 'chaseTimeout': 2, 'bossEntangleMultiplier': .85}
build_defaults = {
    'version':'v12-build-1', 'coauthorRange':3, 'coauthorMultiplier':.6, 'coauthorUpgradeMultiplier':.85,
    'conclusionMultiplier':1.3, 'conclusionUpgradeMultiplier':1.45,
    'sweepRange':2, 'sweepUpgradeRange':2.8, 'sweepAngle':90, 'sweepMultiplier':.6, 'sweepUpgradeMultiplier':.75, 'sweepTargets':2,
    'huntCooldownReduction':3, 'huntUpgradeRange':5.5, 'spreadRange':3, 'spreadUpgradeRange':4.5, 'spreadTargets':2,
    'bloomHealFraction':.02, 'shieldFraction':.05, 'shieldSeconds':6, 'dodgeCooldownMultiplier':.85, 'minimumDodgeCooldown':.5,
    'focusCapacity':15, 'focusRecovery':15, 'edgeMomentum':25, 'healingMultiplier':1.15, 'explorationFocus':2, 'explorationLimit':2,
}
if '--from-runtime' in sys.argv:
    # Ordinary tuning preserves edited runtime values; never reapply example numbers silently.
    out = json.loads(target.read_text(encoding='utf-8-sig'))
    expected = {'version', *mapping.keys(), *local.keys()}
    if set(out) - {'build','beam'} != expected or out['version'] != 'v12-heroes-1':
        raise ValueError('V12 runtime parameter fields/version do not match the implemented mapping')
    if out.get('build') is not None and (set(out['build']) != set(build_defaults) or out['build']['version'] != 'v12-build-1'):
        raise ValueError('V12 build parameter fields/version do not match the implemented mapping')
else:
    pack = json.loads(source.read_text(encoding='utf-8-sig'))
    skills = {s['key']: s['numbers'] for c in pack['characters'] for s in c['skills']}
    out = {'version': 'v12-heroes-1', **{k: skills[s][n] for k,(s,n) in mapping.items()}, **local, 'build':build_defaults}
    target.write_text(json.dumps(out, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
text = json.dumps(out, ensure_ascii=False, separators=(',', ':')).replace('"','""')
generated.write_text('// Generated by Tools/Map-V12Config.py; edit mapped Resources input through the tool.\nnamespace CombatV051.Domain\n{\n    internal static class V12ConfigJson\n    {\n        public const string Text = @"'+text+'";\n    }\n}\n',encoding='utf-8')
report = {'classification':'DESIGN_MAPPING_NOT_UNITY_TEST', 'mode':'runtime-tuning' if '--from-runtime' in sys.argv else 'explicit-design-import', 'source':str(source.relative_to(ROOT)) if source.exists() else None, 'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest() if source.exists() else None,
          'runtime':str(target.relative_to(ROOT)), 'runtimeSha256':hashlib.sha256(target.read_bytes()).hexdigest(), 'fieldMap':mapping, 'localTuning':local,
          'buildMap':'Main spec 5.2/5.3 mapped into V12BuildConfig; descriptive example IDs are explicitly mapped to runtime v12_* and _up IDs by V11BuffCatalog.',
          'buildDefaults':build_defaults, 'buildLocalTuning':{'sweepAngle':90,'minimumDodgeCooldown':.5,'shieldIntegerPolicy':'floor(maxHP*0.05); existing integer absorption pool'},
          'preserved':'Finn sustain remains V11Characters.json finnSustain; Paladin remains original P6 snapshot; old departures do not adopt V12 fields'}
(ROOT/'Reports').mkdir(exist_ok=True)
(ROOT/'Reports/V12_CONFIG_MAPPING.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(target)
