"""Map the authored roster/tree JSON into a pure-domain embedded input.

The Resource is not silently treated as a Unity API or hot-reload setting.
Run this mapping after edits, then compile. Tests compare the exact mapped bytes.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
for source_name, class_name in [('V11Characters.json', 'V11CatalogJson'),
                               ('V11Characters.V11Snapshot.json', 'V11LegacyCatalogJson')]:
    source = ROOT / 'Assets/CombatV051/Resources' / source_name
    destination = ROOT / 'Assets/CombatV051/Domain' / (class_name + '.Generated.cs')
    data = json.loads(source.read_text(encoding='utf-8-sig'))
    text = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    literal = text.replace('"', '""')
    destination.write_text('// Generated by Tools/Map-V11Catalog.py from Resources/' + source_name + '.\n'
                           'namespace CombatV051.Domain\n{\n    internal static class ' + class_name + '\n    {\n'
                           '        public const string Text = @"' + literal + '";\n    }\n}\n', encoding='utf-8')
    print(f'Mapped {len(data["characters"])} characters / {len(data["nodes"])} nodes: {destination}')
