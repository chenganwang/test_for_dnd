"""Map explicit six-room content into the existing DungeonConfig and V12 map metadata.

Initial import uses the retained actual legacy templates, never rewrites their file.
Normal author tuning: edit Resources/V12DungeonConfig.json, then --from-runtime.
"""
from pathlib import Path
import json,sys,hashlib
ROOT=Path(__file__).resolve().parents[1]
resource=ROOT/'Assets/CombatV051/Resources/V12DungeonConfig.json'
generated=ROOT/'Assets/CombatV051/Domain/V12DungeonJson.Generated.cs'
if '--from-runtime' in sys.argv:
    data=json.loads(resource.read_text(encoding='utf-8-sig'))
else:
    cfg=json.loads((ROOT/'Assets/CombatV051/Resources/DungeonConfig.json').read_text(encoding='utf-8-sig'))
    cfg['contentVersion']='dungeon-v12-six-1';cfg['restHealFraction']=.2
    cfg['rooms']=[];cfg['passages']=[]
    centers=[(0,0),(26,0),(52,0),(52,22),(26,22),(0,22)]
    names=['林门前庭','断桥庭院','旧抄写室','倒悬礼堂','露天苗圃','灰冠内庭']
    kinds=['Normal','Normal','Normal','Elite',None,'Boss']
    spawns=[ [('guard-a','guard',5,2),('guard-b','guard',7,-3)],
             [('guard-a','guard',29,-4),('archer','scout',33,4),('guard-b','guard',30,5)],
             [('patrol-a','guard',58,-4),('patrol-b','guard',59,-1)],
             [('elite','elite',56,24),('support','scout',59,18)], [],
             [('boss','boss',3,24),('aid','scout',7,17)] ]
    for i,((x,z),kind,actors) in enumerate(zip(centers,kinds,spawns),1):
        cfg['rooms'].append(dict(id=f'V12_R{i}',encounterKind=kind,x=x,z=z,width=24,depth=20,
          eventIds=['V12_READ','V12_SEARCH'] if i==3 else [],
          enemies=[dict(id=id,templateId=template,x=ax,z=az,bossMechanism=False) for id,template,ax,az in actors]))
    for i in range(5):
        a,b=centers[i],centers[i+1]
        cfg['passages'].append(dict(id=f'V12_P{i+1}{i+2}',roomA=f'V12_R{i+1}',roomB=f'V12_R{i+2}',x=(a[0]+b[0])/2,z=(a[1]+b[1])/2,width=6))
    cfg['events']=[dict(id='V12_READ',roomId='V12_R3',ability='Intelligence',worldEffect='V12_LIBRARY_READ',x=47,z=5,range=2.6,dc=10,preparation=0,advantage=False,disadvantage=False),
                   dict(id='V12_SEARCH',roomId='V12_R3',ability='Wisdom',worldEffect='V12_LIBRARY_CACHE',x=56,z=5,range=2.6,dc=12,preparation=0,advantage=False,disadvantage=False)]
    objectives=['试用本局核心基础动作与关键技，清场后选择形态。','绕过中央遮挡接近射手，两边道路均可通行。','调查两处书架；右下巡逻可绕过，北门无需检定。','击败精英；可选拉绳触发一次落梁，注意友伤。','领取一次休整，完成最后选择，准备首领战。','避开方向重击与地面读条，击败首领后结算。']
    purposes=[dict(roomId=f'V12_R{i+1}',name=names[i],objective=objectives[i],optionalEncounter=i==2,triggerX=57 if i==2 else x,triggerZ=-3 if i==2 else z,triggerRadius=3.6 if i==2 else 0) for i,(x,z) in enumerate(centers)]
    def obstacle(id,room,x,z,w,d,h=1.2,cover=False,flag=None):return dict(id=id,roomId=room,x=x,z=z,width=w,depth=d,height=h,lowCover=cover,removedByFlag=flag)
    obstacles=[obstacle('V12_R2_CENTER','V12_R2',26,0,2,8,2),
               obstacle('V12_R2_COVER','V12_R2',31,2,3,.7,.9,True),
               obstacle('V12_R3_SHELF_A','V12_R3',51,-2,1,7,1.8),
               obstacle('V12_R3_SHELF_B','V12_R3',54,3,5,1,1.8),
               obstacle('V12_R3_SHORTCUT','V12_R3',51,3,1,2,1.8,False,'V12_LIBRARY_READ')]
    points=[dict(id='V12_R1_CAMP',roomId='V12_R1',kind='hub',label='入口营地',x=-7,z=-5,range=3,healFraction=0),
            dict(id='V12_R3_CACHE',roomId='V12_R3',kind='supply',label='一次探索补给',x=47,z=-4,range=2.5,healFraction=.1),
            dict(id='V12_R5_REST',roomId='V12_R5',kind='supply',label='一次休整 · 存活队员20%',x=26,z=22,range=3,healFraction=.2)]
    data=dict(version='v12-six-rooms-1',hash=None,dungeon=cfg,purposes=purposes,obstacles=obstacles,points=points,layoutSlots=[])
    resource.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
if data['version']!='v12-six-rooms-1' or len(data['dungeon']['rooms'])!=6:raise ValueError('Wrong six-room input version/count')
text=json.dumps(data,ensure_ascii=False,separators=(',',':')).replace('"','""')
generated.write_text('// Generated by Tools/Map-V12Dungeon.py from Resources/V12DungeonConfig.json.\nnamespace CombatV051.Domain\n{\n internal static class V12DungeonJson { public const string Text = @"'+text+'"; }\n}\n',encoding='utf-8')
print(str(resource)+' '+hashlib.sha256(resource.read_bytes()).hexdigest())
