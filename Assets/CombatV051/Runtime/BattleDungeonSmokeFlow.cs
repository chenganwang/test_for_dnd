            yield return WaitUntil(() => world.State.mode == CombatMode.PostRollDecision, 5, "Dungeon roll did not reveal.");
            Require(world.State.pendingRoll.id == ticket && raw == CombatJson.Write(world.State.pendingRoll.rawFaces), "Reveal rerolled the paid original result.");
            RestoreExactly("combat-paid-result");
            Capture("03-dungeon-paid-result.png");
            Good(world.Command(CommandKind.Commit, actor: "fighter", target: target, action: "attack", ticket: ticket, id: "p2-smoke/commit-once"), "commit paid dungeon action");
            var replay = world.Command(CommandKind.Commit, actor: "fighter", target: target, action: "attack", ticket: ticket, id: "p2-smoke/commit-once");
            Require(replay.success && replay.duplicate && world.State.charges == charges - 1, "Dungeon Commit replay charged again.");
            Good(world.Command(CommandKind.ExitFocus), "execute committed dungeon action");
            yield return WaitUntil(() => !world.State.queue.Any(q => q.stage == "Queued" || q.stage == "Executing"), 8, "Dungeon queued action did not execute through real Update.");
            Record("dungeon_paid_roll_full_restore_commit", "With an explicitly extended five-second presentation observation fixture, actual Confirm froze all actors/world/camera and paid one shared charge. Original presentation duration was restored before revealing unchanged raw dice; the entire schema4 profile restored identically from disk and committed/executed once through real queue Update. Normal animation timing is not validated by this sample.");
            ClearEncounterFixture("R1", "RESERVE");
            Require(world.Profile.State.meta.challengeUnlocked, "R1 did not unlock challenges.");

            EnterRoomFixture("R2");
            yield return EventFlow("EVENT_A", "04-event-route-result.png");
            EnterRoomFixture("R3"); PrepareCombatFixture("R3-clear", false); ClearEncounterFixture("R3", "FOCUS");
            Require(world.Profile.ActiveMode.HasAbility("SMASH"), "Story R3 did not grant deterministic SMASH ability.");
            yield return EventFlow("EVENT_B", "05-event-boss-result.png");
            EnterRoomFixture("R2");
            PositionFixture("smash-nearby", 48, 8);
            yield return Press(Key.E);
            Require(world.Profile.IsPassageOpen("P24_SMASH") && world.DungeonMap.IsPassageOpen("P24_SMASH"), "Real E near ability gate did not open its physical passage.");
            VerifyDoor("P24_SMASH", false);
            Record("actual_smash_gate", "Story-earned SMASH and recorded nearby geometry enabled real Keyboard E; profile passage and physical collider both opened.");

            EnterRoomFixture("R4"); PrepareCombatFixture("R4-clear", false); ClearEncounterFixture("R4", null);
            EnterRoomFixture("R5"); PrepareCombatFixture("R5-environment", false);
            PositionFixture("elite-cover-nearby", 26, 22);
            var cover = Cover("R5_SHIFT"); var coverBefore = cover.position;
            yield return Press(Key.E);
            Require(world.Profile.ActiveMode.HasFlag("COVER_SHIFTED") && Vector3.Distance(coverBefore, cover.position) > 1 && world.State.Actor(world.State.activeActorId).bonusRemaining > 0,
                "Real E did not spend actor Bonus and move the actual elite cover collider.");
            Capture("06-elite-cover-moved.png");
            Record("actual_environment_cover", "In the real elite room, dedicated E invoked the environment command, moved its layer8 collider and spent one actor Bonus. Source fact and profile flag are persisted.");
            ClearEncounterFixture("R5", "REACTION");
            EnterRoomFixture("R6");
            Fixture("rest-health-deficit", "Lower only friendly HP by five to give the real short-rest UI a measurable effect; no charge/resources are added.", () =>
            { foreach (var actor in world.State.actors) actor.hp = Math.Max(1, actor.hp - 5); });
            PositionFixture("rest-nearby", 0, 22);
            yield return Press(Key.E);
            Require(world.DungeonModal, "E did not open real rest choice UI."); Capture("07-short-rest-choice.png");
            int hpBefore = world.State.actors.Sum(a => a.hp); int restCharge = world.State.charges;
            Choose("rest:heal");
            Require(world.Profile.ActiveMode.usedRestIds.Count == 1 && world.State.actors.Sum(a => a.hp) > hpBefore && world.State.charges == restCharge, "Rest did not heal once without generating charge.");
            var repeatRest = world.ProfileAction(new ProfileCommand { id = Id("repeat-rest"), kind = ProfileCommandKind.ShortRest, selectionId = "heal", actorId = "fighter", qualified = true });
            Require(!repeatRest.success && world.Profile.ActiveMode.usedRestIds.Count == 1, "A second short rest succeeded.");
            PositionFixture("shortcut-inner-nearby", 0, 14); yield return Press(Key.E);
            Require(world.Profile.IsPassageOpen("P60_SHORTCUT") && world.DungeonMap.IsPassageOpen("P60_SHORTCUT"), "E did not open the shortcut from its R6 side.");
            VerifyDoor("P60_SHORTCUT", false);
            Record("rest_once_and_return_shortcut", "Actual rest dialog healed a declared five-HP deficit once without charge gain; repeat refused. Real E opened the return passage from R6 and disabled its collider.");

            EnterRoomFixture("R0"); PositionFixture("hub-nearby", 0, 0); yield return Press(Key.E);
            Require(world.DungeonModal, "E did not open actual mode hub.");
