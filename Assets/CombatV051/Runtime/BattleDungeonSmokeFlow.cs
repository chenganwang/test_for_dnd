    /// <summary>Opt-in -v051-dungeon-smoke only. Commands and declared fixtures, never a human playtest.</summary>
    public sealed class BattleDungeonSmokeFlow : MonoBehaviour
    {
        BattleWorld world;
        string directory;
        Keyboard keyboard;
        InputSettings.BackgroundBehavior previousBackground;
        readonly List<object> checks = new List<object>(), fixtures = new List<object>(), events = new List<object>();
        readonly List<string> errors = new List<string>(), screenshots = new List<string>();
        int sequence;

        public void Begin(BattleWorld owner, string evidenceDirectory)
        {
            Require(Path.IsPathRooted(evidenceDirectory), "P2 smoke requires an absolute, fresh evidence directory.");
            world = owner; directory = Path.GetFullPath(evidenceDirectory);
            Require(!Directory.Exists(directory) || !Directory.EnumerateFileSystemEntries(directory).Any(), "P2 evidence directory is not fresh.");
            Application.runInBackground = true; world.IgnoreApplicationFocus = true;
            previousBackground = InputSystem.settings.backgroundBehavior;
            InputSystem.settings.backgroundBehavior = InputSettings.BackgroundBehavior.IgnoreFocus;
            keyboard = InputSystem.AddDevice<Keyboard>("P2 isolated smoke keyboard");
            InputSystem.EnableDevice(keyboard);
            DisableInput();
            world.Controls.Map.devices = new InputDevice[] { keyboard };
            Application.logMessageReceived += Log;
            StartCoroutine(Run());
        }

        void DisableInput()
        {
            world.Controls.Map.Disable();
            var raycaster = world.Hud.Canvas.GetComponent<UnityEngine.UI.GraphicRaycaster>();
            if (raycaster != null) raycaster.enabled = false;
        }

        void Log(string message, string stack, LogType type)
        {
            if (type == LogType.Error || type == LogType.Exception || type == LogType.Assert) errors.Add(message + "\n" + stack);
        }

        IEnumerator Run()
        {
            Exception failure = null;
            var enumerators = new Stack<IEnumerator>(); enumerators.Push(Flow());
            while (enumerators.Count > 0)
            {
                object value = null; bool next = false;
                try { next = enumerators.Peek().MoveNext(); if (next) value = enumerators.Peek().Current; }
                catch (Exception error) { failure = error; }
                if (failure != null) break;
                if (!next) { enumerators.Pop(); continue; }
                if (value is IEnumerator nested) { enumerators.Push(nested); continue; }
                yield return value;
            }
            if (failure != null) errors.Add(failure.ToString());
            Directory.CreateDirectory(directory);
            Write("summary.json", new
            {
                passed = failure == null && errors.Count == 0, phase = "V051-P2", engine = Application.unityVersion,
                utc = DateTime.UtcNow.ToString("o"), checks, errors, screenshots, fixtures, events,
                captureMode = "OFFSCREEN_RENDER_FIXTURE", normalWindowPresentationVerified = false,
                humanPlayers = 0, humanRuns = 0, usesTestFixtures = true,
                naturalVictoryClaimed = false, naturalTargetDurationVerified = false,
                fixture = "Opt-in scripted World/Profile commands plus isolated real Keyboard E/W input. Explicit party-position, health and AI-timer fixtures skip navigation/grind; enemy HP0 clears are not gameplay victories. Event and combat original dice are generated by real domain RNG and never injected. Real Update, disk persistence and GPU scene rendering remain active.",
                savePath = world.SavePath, graphicsDevice = SystemInfo.graphicsDeviceName,
                width = Screen.width, height = Screen.height
            });
            Application.Quit(failure == null && errors.Count == 0 ? 0 : 2);
        }

