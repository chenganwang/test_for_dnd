        IEnumerator EventFlow(string eventId, string screenshot)
        {
            var template = world.DungeonConfig.Event(eventId);
            PositionFixture(eventId + "-nearby", template.x, template.z);
            yield return Press(Key.E);
            Choose("actor:mage");
            Require(world.Profile.ActiveSafeEvent != null && world.Profile.ActiveSafeEvent.stage == "Quoted", "Event actor choice did not produce a real quote.");
            string combatRandom = CombatJson.Write(world.State.random); int charges = world.State.charges;
            Choose("event-roll");
            Require(world.Profile.ActiveSafeEvent.stage == "AwaitDecision", "Event roll did not persist a decision.");
            bool rerolled = false;
            if (!world.Profile.ActiveSafeEvent.success && world.DungeonChoices.Any(c => c.id == "event-reroll" && c.enabled))
            { int inspiration = world.State.Actor("mage").inspiration; Choose("event-reroll"); Require(world.State.Actor("mage").inspiration == inspiration - 1, "Event reroll did not cost original actor Inspiration."); rerolled = true; }
            var outcome = CombatJson.Clone(world.Profile.ActiveSafeEvent);
            RestoreExactly(eventId + "-result");
            Require(CombatJson.Write(world.Profile.ActiveSafeEvent) == CombatJson.Write(outcome), "Event result changed on complete profile reload.");
            Capture(screenshot);
            Choose("event-accept");
            Require(world.Profile.ActiveSafeEvent == null && world.Profile.ActiveMode.events.Single(e => e.templateId == eventId).stage == "Committed", "Event choice did not finalize success or alternative.");
            Require(world.State.charges == charges && combatRandom == CombatJson.Write(world.State.random), "Safe event drew combat RNG or generated combat charges.");
            Require(world.Profile.ActiveMode.HasFlag(template.worldEffect) == outcome.success, "Event world effect differs from its actual outcome.");
            if (eventId == "EVENT_A")
            {
                var cover = Cover("R4_CENTER");
                Require(Mathf.Abs(cover.position.x - (outcome.success ? 61 : 52)) < .01f, "Event A did not apply its actual central-cover position.");
            }
            events.Add(new { eventId, unforcedOutcome = outcome, rerolled, alternativeUsed = !outcome.success, combatChargesUnchanged = true, combatRandomUnchanged = true });
            Record("event_" + eventId + "_same_result_world_effect", "Actual E/actor selection and independent d20; optional paid failure reroll once; complete profile reload retained exactly the same outcome. Confirm or failure alternative persists the corresponding world effect without combat RNG/charge farming.");
        }

        void EnterRoomFixture(string roomId)
        {
            Require(!world.DungeonModal && world.Profile.CanEnterRoom(roomId), "Fixture cannot skip a locked route into " + roomId);
            var room = world.DungeonConfig.Room(roomId);
            PositionFixture("adjacent-enter-" + roomId, room.x, room.z);
            Good(world.ProfileAction(new ProfileCommand { id = Id("enter-" + roomId), kind = ProfileCommandKind.EnterRoom, roomId = roomId, actorId = world.State.activeActorId, qualified = true }), "enter adjacent " + roomId);
            if (!world.Profile.ActiveRoom.resolved && room.enemies.Count > 0)
                Good(world.ProfileAction(new ProfileCommand { id = Id("activate-" + roomId), kind = ProfileCommandKind.ActivateEncounter, roomId = roomId, actorId = world.State.activeActorId, qualified = true }), "activate actual " + roomId);
            world.Rig.Step(10); Physics.SyncTransforms();
        }

        void PrepareCombatFixture(string name, bool tactical)
        {
            Fixture(name, "Keep actual encounter/enemy templates and random state. Set friendly HP500 and ally Major timers30; quiet enemy AI recovery120. For the first tactical sample put Fighter within two metres of the existing target. These are declared combat fixtures, not naturally earned power or normal victory.", () =>
            {
                foreach (var actor in world.State.actors) { actor.hp = actor.maxHp = 500; actor.majorRemaining = actor.id == "fighter" ? 0 : 30; actor.bonusRemaining = 0; }
                foreach (var enemy in world.State.enemies) { enemy.aiState = 2; enemy.aiRemaining = 120; }
                if (tactical) { var target = world.State.enemies.First(e => e.Alive); var fighter = world.State.Actor("fighter"); fighter.x = target.x - 2; fighter.z = target.z; }
            });
        }

        void ClearEncounterFixture(string room, string preferredRelic)
        {
            Require(world.State.pendingRoll == null && !world.State.queue.Any(q => q.stage == "Queued" || q.stage == "Executing"), "Cannot erase an unresolved tactical action to clear a room.");
            Fixture("hp-zero-clear-" + room, "Set existing enemies HP to zero solely to skip combat grind. ResolveDungeonEncounter still performs the actual Profile resolution, doors, abilities, reward and UI transactions. Not a natural or human victory.", () => { foreach (var enemy in world.State.enemies) enemy.hp = 0; });
            world.ResolveDungeonEncounter();
            Require(!world.Profile.IsInEncounter && world.Profile.ActiveRoom.resolved, "Actual room resolution failed: " + world.Message);
            if (world.Profile.PendingReward == null) return;
            string rewardId = world.Profile.PendingReward.id;
            string selected = world.Profile.PendingReward.candidates.Contains(preferredRelic ?? "") ? preferredRelic : world.Profile.PendingReward.candidates[0];
            bool full = world.Profile.ActiveMode.build.relicSlots.All(r => r != null);
            Choose("reward:" + selected);
            if (full) Choose("replace:0");
            Require(world.Profile.PendingReward == null && world.Profile.ActiveMode.build.relicSlots.Contains(selected), "Real relic UI did not claim/explicitly replace.");
            string id = world.Profile.State.receipts.Last().id;
            var repeat = world.ProfileAction(new ProfileCommand { id = id, kind = ProfileCommandKind.ClaimReward, rewardId = rewardId, selectionId = selected, replacementSlot = full ? 0 : -1 });
            Require(repeat.success && repeat.duplicate && world.Profile.ActiveMode.claimedRewardIds.Count(r => r == rewardId) == 1, "Reward was not idempotent.");
        }

        void ReplaySettlement(string result)
        {
            string id = world.Profile.State.receipts.Last().id; int research = world.Profile.State.meta.research;
            int settlements = world.Profile.State.meta.settledRunIds.Count;
            var replay = world.ProfileAction(new ProfileCommand { id = id, kind = ProfileCommandKind.SettlementOnce, selectionId = result });
            Require(replay.success && replay.duplicate && world.Profile.State.meta.research == research && world.Profile.State.meta.settledRunIds.Count == settlements, "Settlement replay duplicated rewards.");
        }

        void RestoreExactly(string name)
        {
            world.CapturePresentationSnapshot();
            Good(world.ProfileAction(new ProfileCommand { id = Id("save-" + name), kind = ProfileCommandKind.SaveCurrent }), "save complete " + name);
            string before = CombatJson.Write(world.Profile.State);
            WriteRaw(name + "-before-restore.json", before);
            world.ContinueSaved(); DisableInput();
            string after = CombatJson.Write(world.Profile.State);
            WriteRaw(name + "-after-restore.json", after);
            Require(!world.Menu && before == after, "Complete schema4 profile changed during real file reload: " + name);
        }

        void Fixture(string name, string explanation, Action change)
        {
            string evidenceName = (++sequence).ToString("D3") + "-" + name;
            var before = new { profile = world.Profile.State.Clone(), actualCombat = world.State.Clone() };
            change(); Physics.SyncTransforms();
            world.Rig.Step(10);
            Good(world.ProfileAction(new ProfileCommand { id = Id("fixture-" + name), kind = ProfileCommandKind.SaveCurrent }), "persist declared fixture " + name);
            Write(evidenceName + "-fixture-before.json", before); Write(evidenceName + "-fixture-after.json", new { profile = world.Profile.State, actualCombat = world.State });
            fixtures.Add(new { name, evidenceName, explanation, naturalGameplayClaimed = false });
        }

        void PositionFixture(string name, float x, float z)
        {
            Fixture(name, "Place all three actors near an authorized adjacent room or interaction to skip walking time. Does not unlock paths or synthesize interaction success; subsequent World/Profile command checks actual position/progress.", () =>
            { for (int i = 0; i < world.State.actors.Count; i++) { var actor = world.State.actors[i]; actor.x = x + (i == 1 ? -1 : i == 2 ? 1 : 0); actor.z = z - (i == 0 ? 0 : 1); } });
        }

        IEnumerator Press(Key key, float heldSeconds = .04f)
        {
            world.Controls.Map.Enable();
            InputSystem.QueueStateEvent(keyboard, new KeyboardState(key));
            yield return null; yield return new WaitForSecondsRealtime(heldSeconds);
            InputSystem.QueueStateEvent(keyboard, new KeyboardState());
            yield return null; yield return null;
            world.Controls.Map.Disable();
        }

        void Choose(string id)
        {
            Require(world.DungeonChoices.Any(c => c.id == id && c.enabled), "Expected enabled real UI option missing: " + id + "; " + world.DungeonDialogTitle);
            world.ChooseDungeonOption(id);
        }
        void VerifyDoor(string id, bool expectedEnabled)
        {
            var colliders = world.DungeonMap.GetComponentsInChildren<Collider>(true).Where(c => c.name.Contains(id) && c.gameObject.layer == 8).ToArray();
            Require(colliders.Length > 0 && colliders.All(c => c.enabled == expectedEnabled), "Door collider state disagrees for " + id);
        }
        Transform Cover(string id) => world.DungeonMap.GetComponentsInChildren<Transform>(true).Single(t => t.name == "Cover " + id);
        Vector3 Position(string id) { var actor = world.State.Actor(id); return new Vector3(actor.x, actor.heightY, actor.z); }
        string Id(string label) => "p2-smoke/" + (++sequence) + "/" + label;
        void Record(string name, string detail) => checks.Add(new { name, passed = true, detail });
        static void Require(bool condition, string message) { if (!condition) throw new InvalidOperationException(message); }
        static void Good(CombatResult result, string step) => Require(result != null && result.success, step + ": " + result?.reason);
        static void Good(ProfileResult result, string step) => Require(result != null && result.success, step + ": " + result?.reason);
        void Write(string name, object value) => WriteRaw(name, Newtonsoft.Json.JsonConvert.SerializeObject(value, Newtonsoft.Json.Formatting.Indented));
        void WriteRaw(string name, string value) => File.WriteAllText(Path.Combine(directory, name), value);
        IEnumerator WaitUntil(Func<bool> predicate, float seconds, string failure)
        {
            float deadline = Time.realtimeSinceStartup + seconds;
            while (!predicate() && Time.realtimeSinceStartup < deadline) yield return null;
            Require(predicate(), failure);
        }

        void Capture(string filename)
        {
            world.Hud.RefreshView();
            var camera = world.BattleCamera; var canvas = world.Hud.Canvas;
            var oldMode = canvas.renderMode; var oldCamera = canvas.worldCamera; var oldDistance = canvas.planeDistance;
            var oldSort = canvas.sortingOrder; var oldOverride = canvas.overrideSorting;
            var oldActive = RenderTexture.active; var oldTarget = camera.targetTexture;
            var target = RenderTexture.GetTemporary(Screen.width, Screen.height, 24, RenderTextureFormat.ARGB32, RenderTextureReadWrite.sRGB);
            Texture2D texture = null;
            try
            {
                camera.targetTexture = target; canvas.renderMode = RenderMode.ScreenSpaceCamera;
                canvas.worldCamera = camera; canvas.planeDistance = 1; canvas.overrideSorting = true; canvas.sortingOrder = short.MaxValue;
                Canvas.ForceUpdateCanvases();
                RenderPipeline.SubmitRenderRequest(camera, new RenderPipeline.StandardRequest { destination = target });
                RenderTexture.active = target;
                texture = new Texture2D(target.width, target.height, TextureFormat.RGBA32, false);
                texture.ReadPixels(new Rect(0, 0, target.width, target.height), 0, 0, false); texture.Apply(false, false);
                var pixels = texture.GetPixels32(); var colors = new HashSet<int>(); int lit = 0;
                for (int i = 0; i < pixels.Length; i += 13)
                { var p = pixels[i]; colors.Add(p.r * 65536 + p.g * 256 + p.b); if (p.r > 20 || p.g > 20 || p.b > 20) lit++; }
                File.WriteAllBytes(Path.Combine(directory, filename), texture.EncodeToPNG());
                Require(colors.Count > 20 && lit > pixels.Length / 1000, "P2 actual offscreen capture lacks rendered detail.");
                screenshots.Add(filename);
            }
            finally
            {
                camera.targetTexture = oldTarget; RenderTexture.active = oldActive;
                canvas.renderMode = oldMode; canvas.worldCamera = oldCamera; canvas.planeDistance = oldDistance;
                canvas.overrideSorting = oldOverride; canvas.sortingOrder = oldSort;
                RenderTexture.ReleaseTemporary(target); if (texture != null) Destroy(texture);
            }
        }

        void OnDestroy()
        {
            Application.logMessageReceived -= Log;
            if (keyboard != null && keyboard.added) InputSystem.RemoveDevice(keyboard);
            if (keyboard != null) InputSystem.settings.backgroundBehavior = previousBackground;
        }
