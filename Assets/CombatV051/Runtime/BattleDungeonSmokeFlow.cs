            Require(Time.timeScale == 0, "World scale was nonzero during actual RollFreeze.");
            Require(world.RollElapsed > 0, "Unscaled roll presentation did not advance while frozen.");
            Require(frozen == frozenAfter, "Actor/AI/world snapshot mutated during actual RollFreeze; see separate before/after evidence.");
            Require(Vector3.Distance(cameraPosition, world.BattleCamera.transform.position) < .0001f && Quaternion.Angle(cameraRotation, world.BattleCamera.transform.rotation) < .01f, "Dungeon camera moved during RollFreeze.");
