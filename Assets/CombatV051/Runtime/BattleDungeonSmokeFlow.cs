            world.InitializeDungeonForTests(Path.Combine(directory, "Profiles", "dungeon.json"), "p2-smoke", true);
            DisableInput();
            Require(world.Profile != null && !world.Menu && world.DungeonMap != null, "Actual P2 profile/map did not initialize.");
            Require(Path.GetFullPath(world.SavePath).StartsWith(directory + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase), "P2 save escaped evidence directory.");
            Require(world.Profile.State.schemaVersion == 4 && world.DungeonConfig.rooms.Count == 8 && world.State.actors.Count == 3,
                "P2 must initialize schema4, eight actual rooms and three actors.");
            Choose("close");
            var initial = Position(world.State.activeActorId);
