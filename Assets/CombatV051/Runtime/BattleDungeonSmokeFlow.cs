            EnterRoomFixture("R1");
            Require(world.Profile.IsInEncounter && !world.DungeonMap.IsPassageOpen("P01") && !world.DungeonMap.IsPassageOpen("P12"), "R1 encounter did not close both physical doors.");
            PrepareCombatFixture("R1-combat", true);
            var target = world.State.enemies.First(e => e.Alive).id;
            int charges = world.State.charges;
            Good(world.Command(CommandKind.EnterFocus), "enter actual dungeon combat focus");
            Good(world.SelectCommandActor("fighter"), "select Fighter");
            world.SelectedTarget = target; world.SelectedAction = "attack";
            Require(!world.QuickDice, "This explicit freeze observer expects the ordinary presentation path.");
