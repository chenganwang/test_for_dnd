                realTime = Time.realtimeSinceStartup, realTimeDelta = Time.realtimeSinceStartup - observationStart,
                worldScale = Time.timeScale,
                cameraPosition = new { world.BattleCamera.transform.position.x, world.BattleCamera.transform.position.y, world.BattleCamera.transform.position.z },
